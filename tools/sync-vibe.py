#!/usr/bin/env python3
"""
sync-vibe.py — Regenerate Vibe-compatible files from canonical .agents/ source.

Reads:
  .agents/agents/*.md   → .vibe/plugins/ocgs/ai.mistral.vibe/agents/*.toml
  opencode.json (mcp)   → .vibe/config.toml [[mcp_servers]] section

Usage:
  python3 tools/sync-vibe.py           # sync agents + mcp
  python3 tools/sync-vibe.py --check   # check if sync needed (exit 1 if stale)
"""

import json
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
AGENTS_SRC = ROOT / ".agents" / "agents"
AGENTS_DST = ROOT / ".vibe" / "plugins" / "ocgs" / "ai.mistral.vibe" / "agents"
OPENCODE_JSON = ROOT / "opencode.json"
CONFIG_TOML = ROOT / ".vibe" / "config.toml"
RULES_SRC = ROOT / ".agents" / "rules"


# ─── Helpers ───────────────────────────────────────────────────────────────

def parse_frontmatter(content: str):
    """Parse YAML frontmatter (simple key: value) and return (dict, body)."""
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", content, re.DOTALL)
    if not m:
        return {}, content
    fm = {}
    for line in m.group(1).split("\n"):
        km = re.match(r"^(\w[\w-]*)\s*:\s*(.*)$", line)
        if km:
            val = km.group(2).strip()
            if (val.startswith('"') and val.endswith('"')) or (val.startswith("'") and val.endswith("'")):
                val = val[1:-1]
            fm[km.group(1)] = val
    return fm, m.group(2)


def kebab_to_title(slug: str) -> str:
    return " ".join(w.capitalize() for w in slug.split("-"))


def toml_escape_string(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def toml_literal(body: str) -> str:
    """Use TOML multi-line literal string (triple single-quote)."""
    if "'''" in body:
        # Fallback: escaped basic string if literal won't work
        return '"' + toml_escape_string(body) + '"'
    return f"'''{body}'''"


def truncate_description(desc: str, limit: int = 300) -> str:
    """Truncate to limit chars at a word boundary, adding ellipsis if cut."""
    if len(desc) <= limit:
        return desc
    ellipsis = "..."
    cut = desc[:limit - len(ellipsis)]
    # Try to cut at the last space to avoid mid-word truncation
    last_space = cut.rfind(" ")
    if last_space > limit - len(ellipsis) - 50:
        cut = cut[:last_space]
    return cut.rstrip(".,;:") + ellipsis


def determine_safety(slug: str) -> str:
    destructive = {"prototyper"}
    if slug in destructive:
        return "neutral"
    return "safe"


def determine_tools(slug: str) -> list:
    base = ["read_file", "grep", "write_file", "edit"]
    coders = {
        "gameplay-programmer", "engine-programmer", "ai-programmer",
        "network-programmer", "tools-programmer", "ui-programmer",
        "prototyper", "devops-engineer", "analytics-engineer",
        "security-engineer",
    }
    testers = {"qa-tester", "qa-lead", "performance-analyst"}
    if slug in coders or slug in testers:
        return base + ["bash"]
    return base


# ─── Agent conversion ──────────────────────────────────────────────────────

def convert_agent(src_path: Path, slug: str, include_max_turns: bool = True) -> str:
    content = src_path.read_text(encoding="utf-8")
    fm, body = parse_frontmatter(content)

    description = truncate_description(fm.get("description", ""))
    display_name = kebab_to_title(slug)
    safety = determine_safety(slug)
    tools = determine_tools(slug)
    instructions = body.strip()
    # OCGS frontmatter uses camelCase `maxTurns`; Vibe profiles use `max_turns`
    max_turns = fm.get("maxTurns", "").strip()

    lines = [
        'schema_version = 1',
        'agent_type = "subagent"',
        f'display_name = "{toml_escape_string(display_name)}"',
        f'description = "{toml_escape_string(description)}"',
        f'safety = "{safety}"',
        f'enabled_tools = [{", ".join(f"{chr(34)}{t}{chr(34)}" for t in tools)}]',
    ]
    if include_max_turns and max_turns.isdigit():
        lines.append(f'max_turns = {int(max_turns)}')
    lines.append(f'instructions = {toml_literal(instructions)}')
    return "\n".join(lines) + "\n"


def sync_agents(check_only: bool = False) -> dict:
    AGENTS_DST.mkdir(parents=True, exist_ok=True)
    count = 0
    stale = 0

    for src_file in sorted(AGENTS_SRC.glob("*.md")):
        slug = src_file.stem
        dst_path = AGENTS_DST / f"{slug}.toml"
        # The plugin loader validates agent TOMLs with extra="forbid"
        # (_PluginAgentDocument in vibe/core/plugins/_native.py) and does not
        # accept max_turns, so it must not be emitted for plugin agents.
        # Registry-style profiles (.vibe/agents/, generated by the copy
        # scripts) do accept max_turns.
        toml = convert_agent(src_file, slug, include_max_turns=False)

        if check_only and dst_path.exists():
            existing = dst_path.read_text(encoding="utf-8")
            if existing != toml:
                print(f"  stale: {slug}.toml")
                stale += 1
            continue

        dst_path.write_text(toml, encoding="utf-8")
        count += 1

    if not check_only:
        print(f"Synced {count} agents → {AGENTS_DST}")
    return {"count": count, "stale": stale}


# ─── MCP conversion ─────────────────────────────────────────────────────────

def sync_mcp(check_only: bool = False) -> dict:
    """Generate [[mcp_servers]] TOML blocks from opencode.json and merge into config.toml."""
    if not OPENCODE_JSON.exists():
        print("No opencode.json found, skipping MCP sync")
        return {"stale": 0}

    config = json.loads(OPENCODE_JSON.read_text(encoding="utf-8"))

    # Build TOML blocks for enabled MCP servers
    blocks = []
    for name, server in config.get("mcp", {}).items():
        if server.get("enabled") is False:
            continue
        lines = [f'[[mcp_servers]]', f'name = "{name}"']
        if server.get("url"):
            lines.append(f'transport = "streamable-http"')
            lines.append(f'url = "{server["url"]}"')
        elif server.get("command"):
            lines.append(f'transport = "stdio"')
            lines.append(f'command = "{server["command"][0]}"')
            args = server["command"][1:]
            if args:
                args_str = ", ".join(f'"{a}"' for a in args)
                lines.append(f'args = [{args_str}]')
            if server.get("environment"):
                lines.append("")
                lines.append(f'[mcp_servers.env]')
                for k, v in server["environment"].items():
                    v_expanded = re.sub(r"\{env:([^}]+)\}", r"${\1}", v)
                    lines.append(f'{k} = "{v_expanded}"')
        blocks.append("\n".join(lines))

    # Build the MCP section to append/update in config.toml
    mcp_section = "# MCP servers — synced from opencode.json by tools/sync-vibe.py.\n"
    if blocks:
        mcp_section += "\n\n".join(blocks) + "\n"
    else:
        mcp_section += "# (no enabled MCP servers in opencode.json)\n"

    # Read existing config.toml, replace any MCP section (from first MCP marker to end)
    MCP_MARKER = "# MCP servers"
    existing = ""
    if CONFIG_TOML.exists():
        existing = CONFIG_TOML.read_text(encoding="utf-8")

    # Remove old MCP section (from marker to end of file)
    idx = existing.find(MCP_MARKER)
    if idx != -1:
        base = existing[:idx].rstrip() + "\n"
    else:
        base = existing.rstrip() + "\n" if existing else ""

    new_config = base + "\n" + mcp_section

    if check_only:
        if CONFIG_TOML.exists():
            current = CONFIG_TOML.read_text(encoding="utf-8")
            if current != new_config:
                print("  stale: config.toml (MCP section)")
                return {"stale": 1}
        return {"stale": 0}

    CONFIG_TOML.write_text(new_config, encoding="utf-8")
    print(f"Synced MCP servers → {CONFIG_TOML}")
    return {"stale": 0}


# ─── Rules summary ─────────────────────────────────────────────────────────

def print_rules_summary():
    if not RULES_SRC.exists():
        return
    files = sorted(RULES_SRC.glob("*.md"))
    print(f"\nRules available in .agents/rules/ (consolidate into AGENTS.md manually):")
    for f in files:
        content = f.read_text(encoding="utf-8")
        fm, _ = parse_frontmatter(content)
        paths = f" [{fm.get('paths', '')}]" if fm.get("paths") else ""
        print(f"  {f.name}{paths}")


# ─── Main ───────────────────────────────────────────────────────────────────

def main():
    check_only = "--check" in sys.argv
    print("Checking Vibe sync status..." if check_only else "Syncing OCGS → Vibe...")

    agent_result = sync_agents(check_only)
    mcp_result = sync_mcp(check_only)

    if not check_only:
        print_rules_summary()

    if check_only:
        total_stale = agent_result["stale"] + mcp_result["stale"]
        if total_stale > 0:
            print(f"\n{total_stale} file(s) need sync. Run: python3 tools/sync-vibe.py")
            sys.exit(1)
        else:
            print("\nAll Vibe files up to date.")


if __name__ == "__main__":
    main()
